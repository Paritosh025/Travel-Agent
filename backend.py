# Flight Tool Router Prompt
FLIGHT_AGENT_PROMPT = """
You are a travel flight expert.

User Query:
{query}

Live web and route information:
{flight_search_data}

Create a practical flight comparison with multiple options when reliable options are available.
For each option, include only when verified:
1. Origin airport and destination airport
2. Airline
3. Direct or connecting
4. Number of stops and layover airport(s)
5. Total journey duration
6. Typical or live fare range
7. Booking or airline link

Do not fabricate departure times, arrival times, return times, schedules, or exact fares.
Prefer route and duration details over exact times unless the source provides them.
Clearly label fare ranges as live, typical, or estimated.
"""




# Flight Agent
def flight_agent(state: TravelState):
    print("\nINSIDE FLIGHT AGENT\n")

    query = state["user_query"]

    try:
        flight_search_data = asyncio.run(
            tavily_mcp_search(
                f"Find several practical flight options for this travel request: {query}. "
                "Include origin and destination airports, airlines, direct or connecting status, "
                "stops and layovers, total journey duration, fare range, and booking links. "
                "Do not include uncertain or invented departure or arrival times."
            )
        )

        print("\nFLIGHT SEARCH:", str(flight_search_data)[:1000])

        prompt = FLIGHT_AGENT_PROMPT.format(
            query=query,
            flight_search_data=str(flight_search_data)[:6000]
        )

        response = llm.invoke([
            SystemMessage(
                content="You are an expert travel flight planner."
            ),
            HumanMessage(content=prompt)
        ])

        flight_data = response.content

    except Exception as e:

        flight_data = f"Flight information unavailable: {str(e)}"

    return {
        "flight_results": flight_data,
        "messages": [
            AIMessage(
                content="Flight recommendations generated"
            )
        ],
        "llm_calls": state.get("llm_calls", 0) + 1
    }





