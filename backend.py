def final_agent(state: TravelState):
    final_prompt = f"""
Generate the final travel response for the user.

User Request:
{state['user_query']}

Flights:
{state['flight_results']}

Hotels:
{state['hotel_results']}

Weather:
{state['weather_results']}

Itinerary:
{state['itinerary']}

Format the final answer beautifully using these sections:

1. Trip Summary
2. Flight Information
3. Hotel Suggestions
4. Weather Information
5. Day-by-Day Itinerary
6. Estimated Budget
7. Final Recommendations


Important:
- Be clear and practical.
- Present multiple flight options with airline, direct/connecting status, stops, and duration. Do not invent exact departure or arrival times.
- Recommend 3 to 5 hotels per city, not only two hotels for the whole trip.
- Include neighborhood, amenities, estimated price range, and booking source for hotels.
- Label fares and prices as live, typical, or estimated.
- Provide a concise 7-day destination weather summary with highs, lows, conditions, rain chance, and practical packing advice when available.
- Include weather-based travel advice.
- Keep the response useful for real travel planning.
"""

    response = llm.invoke([
        SystemMessage(content="You are a professional AI travel booking assistant."),
        HumanMessage(content=final_prompt)
    ])

    return {
        "messages": [response],
        "llm_calls": state.get("llm_calls", 0) + 1
    }


