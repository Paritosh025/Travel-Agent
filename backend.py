def hotel_agent(state: TravelState):
    query = (
        f"Find hotel options for this travel request: {state['user_query']}. "
        "For every city mentioned, recommend 3 to 5 hotels across budget, mid-range, "
        "and premium categories. Include neighborhood, nearby attractions or transport, "
        "main amenities, estimated nightly price if available, and a booking link. "
        "Prioritize current, reputable sources and clearly distinguish live prices from estimates."
    )
    hotel_results = asyncio.run(tavily_mcp_search(query))

    return {
        "hotel_results": hotel_results,
        "messages": [
            AIMessage(content="Hotel information fetched.")
        ],
        "llm_calls": state.get("llm_calls", 0) + 1
    }




# =========================
# Weather Agent
# =========================

def weather_agent(state: TravelState):

    city = extract_destination(state["user_query"])

    weather_data = asyncio.run(
        weather_mcp_search(city)
    )

    forecast_data = asyncio.run(
        forecast_mcp_search(city)
    )

    extended_forecast = asyncio.run(
        tavily_mcp_search(
            f"Current and 7-day weather forecast for {city}. "
            "Summarize each day with expected high and low temperature, condition, rain chance, "
            "humidity or wind when available, and practical packing advice."
        )
    )

    return {
        "weather_results": f"""
        Current Weather:
        {weather_data}

        Forecast Data:
        {forecast_data}

        7-Day Weather Search:
        {extended_forecast}
        """,
        "messages": [
            AIMessage(
                content="Weather information fetched"
            )
        ]
    }




